"""Convert a TTF font to an Adafruit GFX font header (like fontconvert).

Use it for sizes the built-in GFX fonts don't have, e.g. the big clock.
Only include the characters you need to keep flash usage small.

Example:
    python tools/fontgen/make_gfx_font.py FreeSansBold.ttf 148 "-:" ClockFont src/ui/fonts/ClockFont.h

    size   font size in pixels (FreeSans cap height is about 0.73 x size)
    chars  first and last character of the range, e.g. "-:" = - . / 0-9 :

Needs Pillow (pip install pillow).
"""

import sys

from PIL import Image, ImageDraw, ImageFont


def render_glyph(font, ch):
    advance = round(font.getlength(ch))

    # Draw on a big canvas with the pen at (origin, origin), then crop to the ink
    origin = font.size * 2
    canvas = Image.new("L", (origin * 3, origin * 3), 0)
    ImageDraw.Draw(canvas).text((origin, origin), ch, font=font, fill=255, anchor="ls")
    canvas = canvas.point(lambda value: 255 if value >= 128 else 0)

    box = canvas.getbbox()
    if box is None:
        return [], 0, 0, advance, 0, 0  # e.g. space

    x0, y0, x1, y1 = box
    width, height = x1 - x0, y1 - y0
    pixels = canvas.load()
    bits = [1 if pixels[x, y] else 0 for y in range(y0, y1) for x in range(x0, x1)]

    return bits, width, height, advance, x0 - origin, y0 - origin


def pack_bits(bits):
    # GFX glyphs are bit-packed MSB first with no padding between rows
    data = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        data.append(sum(bit << (7 - n) for n, bit in enumerate(chunk)))
    return data


def main():
    if len(sys.argv) != 6:
        print(__doc__)
        sys.exit(1)

    ttf, size, chars, name, output = sys.argv[1:]
    first, last = ord(chars[0]), ord(chars[-1])
    font = ImageFont.truetype(ttf, int(size))

    bitmap, glyphs = [], []
    for code in range(first, last + 1):
        bits, width, height, advance, x_offset, y_offset = render_glyph(font, chr(code))
        glyphs.append((len(bitmap), width, height, advance, x_offset, y_offset, chr(code)))
        bitmap += pack_bits(bits)

    ascent, descent = font.getmetrics()

    lines = [
        "#pragma once",
        "",
        f"// Generated by tools/fontgen/make_gfx_font.py from {ttf.split('/')[-1].split(chr(92))[-1]}",
        f"// Size {size} px, characters '{chr(first)}' to '{chr(last)}'",
        "",
        "#include <Adafruit_GFX.h>",
        "",
        f"const uint8_t {name}Bitmaps[] PROGMEM = {{",
    ]
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
    lines += ["};", "", f"const GFXglyph {name}Glyphs[] PROGMEM = {{"]
    for offset, width, height, advance, x_offset, y_offset, ch in glyphs:
        lines.append(f"    {{{offset}, {width}, {height}, {advance}, {x_offset}, {y_offset}}},  // '{ch}'")
    lines += [
        "};",
        "",
        f"const GFXfont {name} PROGMEM = {{",
        f"    (uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, 0x{first:02X}, 0x{last:02X}, {ascent + descent}",
        "};",
        "",
    ]

    with open(output, "w", newline="\n") as file:
        file.write("\n".join(lines))
    print(f"Saved {output}: {last - first + 1} glyphs, {len(bitmap)} bytes")


if __name__ == "__main__":
    main()
